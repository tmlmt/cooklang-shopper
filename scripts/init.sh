#!/usr/bin/env bash
set -euo pipefail

SYSTEMD=false
PM2=false

while [[ $# -gt 0 ]]; do
  case "$1" in
    --pm2)
      PM2=true
      shift
      ;;
    --systemd)
      SYSTEMD=true
      shift
      ;;
    -h|--help)
      cat <<EOF
Usage: $(basename "$0") [--systemd | --pm2]

Initialize Cooklang Shopper secrets.

Options:
  --systemd  Create or update the protected systemd environment file.
  --pm2      Create a pm2 ecosystem file (ecosystem.config.cjs) with a generated app secret.
  -h, --help Show this help message.
EOF
      exit 0
      ;;
    *)
      printf 'ERROR: Unknown option: %s\n' "$1" >&2
      exit 1
      ;;
  esac
done

SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
if [[ -f "$SCRIPT_DIR/config.yaml.example" ]]; then
  APP_DIR="$SCRIPT_DIR"
elif [[ -f "$SCRIPT_DIR/../config.yaml.example" ]]; then
  APP_DIR="$(cd -- "$SCRIPT_DIR/.." && pwd)"
else
  printf 'ERROR: Could not find config.yaml.example next to the script.\n' >&2
  exit 1
fi

CONFIG_FILE="$APP_DIR/config.yaml"
EXAMPLE_FILE="$APP_DIR/config.yaml.example"

if ! command -v openssl >/dev/null 2>&1; then
  printf 'ERROR: openssl is required to generate secure secrets.\n' >&2
  exit 1
fi

if [[ "$SYSTEMD" == true && "$PM2" == true ]]; then
  printf 'ERROR: --systemd and --pm2 cannot be used together.\n' >&2
  exit 1
fi

SUDO=()
if [[ "$SYSTEMD" == true && "$EUID" -ne 0 ]]; then
  if ! command -v sudo >/dev/null 2>&1; then
    printf 'ERROR: sudo is required to create the systemd environment file.\n' >&2
    exit 1
  fi
  sudo -v
  SUDO=(sudo -n)
fi

SESSION_SECRET=""
CONFIG_CREATED=false
if [[ ! -f "$CONFIG_FILE" ]]; then
  SESSION_SECRET="$(openssl rand -hex 32)"
  TMP_CONFIG="$(mktemp "$APP_DIR/.config.yaml.XXXXXX")"
  trap 'rm -f "${TMP_CONFIG:-}"' EXIT
  SESSION_SECRET="$SESSION_SECRET" awk '
    BEGIN { secret = ENVIRON["SESSION_SECRET"] }
    /^sessionSecret[[:space:]]*:/ {
      print "sessionSecret: \"" secret "\""
      found = 1
      next
    }
    { print }
    END {
      if (!found) {
        print ""
        print "sessionSecret: \"" secret "\""
      }
    }
  ' "$EXAMPLE_FILE" > "$TMP_CONFIG"
  chmod 600 "$TMP_CONFIG"
  mv "$TMP_CONFIG" "$CONFIG_FILE"
  trap - EXIT
  CONFIG_CREATED=true
  printf 'Created %s from the example configuration.\n' "$CONFIG_FILE"
  printf 'Generated sessionSecret in %s.\n' "$CONFIG_FILE"
fi

if [[ "$CONFIG_CREATED" == true ]]; then
  :
elif ! grep -Eq '^sessionSecret[[:space:]]*:' "$CONFIG_FILE"; then
  SESSION_SECRET="$(openssl rand -hex 32)"
  if [[ -s "$CONFIG_FILE" && "$(tail -c 1 "$CONFIG_FILE" | wc -l)" -eq 0 ]]; then
    printf '\n' >> "$CONFIG_FILE"
  fi
  printf '# Secret used to encrypt session cookies (generated by init.sh).\n' >> "$CONFIG_FILE"
  printf 'sessionSecret: "%s"\n' "$SESSION_SECRET" >> "$CONFIG_FILE"
  printf 'Added a generated sessionSecret to %s.\n' "$CONFIG_FILE"
else
  printf 'Preserved the existing sessionSecret in %s.\n' "$CONFIG_FILE"
fi

if [[ "$PM2" == true ]]; then
  ECOSYSTEM_FILE="$APP_DIR/ecosystem.config.cjs"
  if [[ -f "$ECOSYSTEM_FILE" ]]; then
    printf 'Preserved the existing %s.\n' "$ECOSYSTEM_FILE"
  else
    TMP_ECO="$(mktemp "$APP_DIR/.ecosystem.XXXXXX")"
    trap 'rm -f "${TMP_ECO:-}"' EXIT
    cat > "$TMP_ECO" <<EOF
module.exports = {
  apps: [
    {
      cwd: '$APP_DIR',
      script: './server/index.mjs',
      watch: './nitro.json',
      name: 'CooklangShopper',
      exec_mode: 'cluster',
      instances: 1,
      merge_logs: true,
      log_date_format: 'YYYY-MM-DD HH:mm:ss',
      env: {
        NODE_ENV: 'production',
        NUXT_APP_SECRET: '$(openssl rand -hex 32)',
      },
    },
  ],
}
EOF
    chmod 600 "$TMP_ECO"
    mv "$TMP_ECO" "$ECOSYSTEM_FILE"
    trap - EXIT
    printf 'Created %s with a generated NUXT_APP_SECRET.\n' "$ECOSYSTEM_FILE"
  fi
  printf 'SUCCESS: Initialization complete. When ready, run: pm2 start %s && pm2 save\n' "$ECOSYSTEM_FILE"
elif [[ "$SYSTEMD" == true ]]; then
  ENV_DIR="/etc/cooklang-shopper"
  ENV_FILE="$ENV_DIR/cooklang-shopper.env"

  "${SUDO[@]}" install -d -o root -g root -m 700 "$ENV_DIR"

  EXISTING_ENV=""
  if "${SUDO[@]}" test -f "$ENV_FILE"; then
    EXISTING_ENV="$("${SUDO[@]}" cat "$ENV_FILE")"
  fi

  APP_SECRET=""
  while IFS= read -r line; do
    case "$line" in
      NUXT_APP_SECRET=*)
        value="${line#NUXT_APP_SECRET=}"
        if [[ -z "$APP_SECRET" && -n "$value" ]]; then
          APP_SECRET="$value"
        fi
        ;;
    esac
  done <<< "$EXISTING_ENV"
  if [[ -z "$APP_SECRET" ]]; then
    APP_SECRET="$(openssl rand -hex 32)"
  fi

  TMP_ENV="$(mktemp)"
  trap 'rm -f "${TMP_ENV:-}"' EXIT
  {
    printf 'NODE_ENV=production\n'
    printf 'NUXT_APP_SECRET=%s\n' "$APP_SECRET"
    while IFS= read -r line; do
      case "$line" in
        NODE_ENV=*|NUXT_APP_SECRET=*) ;;
        *) [[ -z "$line" ]] || printf '%s\n' "$line" ;;
      esac
    done <<< "$EXISTING_ENV"
  } > "$TMP_ENV"
  chmod 600 "$TMP_ENV"
  "${SUDO[@]}" install -o root -g root -m 600 "$TMP_ENV" "$ENV_FILE"
  rm -f "$TMP_ENV"
  trap - EXIT

  printf 'Systemd environment configured at %s with root-only permissions.\n' "$ENV_FILE"
  printf 'SUCCESS: Initialization complete. Continue the installation guide to install and configure the service.\n'
  printf 'When ready to start it persistently, run: sudo systemctl daemon-reload && sudo systemctl enable --now cooklang-shopper\n'
else
  printf 'SUCCESS: Initialization complete. Continue the installation guide to finish configuring Cooklang Shopper.\n'
fi
